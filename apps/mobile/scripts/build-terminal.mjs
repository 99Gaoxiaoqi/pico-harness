import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { createRequire } from "node:module";
import { terminalTheme } from "../src/palette.ts";
const require = createRequire(import.meta.url);
const root = resolve(import.meta.dirname, "..");
const result = await build({
  entryPoints: [resolve(root, "src/terminal-web.ts")],
  bundle: true,
  write: false,
  minify: true,
  platform: "browser",
});
const css = await readFile(require.resolve("@xterm/xterm/css/xterm.css"), "utf8");
const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; script-src 'unsafe-inline'; connect-src 'none'; img-src data:"><style>${css}:root{--terminal-bg:${terminalTheme.background};--terminal-fg:${terminalTheme.foreground};color-scheme:light}html,body,#terminal{margin:0;width:100%;height:100%;background:var(--terminal-bg);color:var(--terminal-fg);overflow:hidden}.xterm .xterm-viewport,.xterm .composition-view{background:var(--terminal-bg);color:var(--terminal-fg)}</style></head><body><div id="terminal"></div><script>${js}</script></body></html>`;
await writeFile(
  resolve(root, "src/terminal.generated.ts"),
  `// Generated by scripts/build-terminal.mjs; local resources only.\nexport default ${JSON.stringify(html)};\n`,
);
