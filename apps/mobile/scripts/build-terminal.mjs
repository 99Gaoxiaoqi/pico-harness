import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, "..");
const result = await build({
  stdin: {
    contents: `import { Terminal } from '@xterm/xterm'; import { FitAddon } from '@xterm/addon-fit'; const term=new Terminal({cursorBlink:true,fontSize:13,theme:{background:'#10141c',foreground:'#edf2fa'}});const fit=new FitAddon();term.loadAddon(fit);term.open(document.getElementById('terminal'));const send=(v)=>window.ReactNativeWebView.postMessage(JSON.stringify(v));term.onData(data=>send({type:'input',data}));term.onResize(size=>send({type:'resize',...size}));function receive(e){try{const m=JSON.parse(e.data);if(m.type==='output'){if(m.reset)term.reset();term.write(m.data);}if(m.type==='key')term.input(m.data,true);if(m.type==='focus')term.focus();}catch{}}window.addEventListener('message',receive);document.addEventListener('message',receive);new ResizeObserver(()=>fit.fit()).observe(document.body);fit.fit();send({type:'ready'});`,
    resolveDir: root,
    loader: "js",
  },
  bundle: true,
  write: false,
  minify: true,
  platform: "browser",
});
const css = await readFile(resolve(root, "node_modules/@xterm/xterm/css/xterm.css"), "utf8");
const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; script-src 'unsafe-inline'; connect-src 'none'; img-src data:"><style>${css}html,body,#terminal{margin:0;width:100%;height:100%;background:#10141c;overflow:hidden}</style></head><body><div id="terminal"></div><script>${js}</script></body></html>`;
await writeFile(
  resolve(root, "src/terminal.generated.ts"),
  `// Generated by scripts/build-terminal.mjs; local resources only.\nexport default ${JSON.stringify(html)};\n`,
);
